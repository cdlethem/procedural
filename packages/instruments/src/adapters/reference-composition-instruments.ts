type Condition = Record<string, readonly (string | number | boolean)[]>;
function control(parameter: Parameter, visibleWhen?: Condition): Parameter {
  return visibleWhen ? { ...parameter, visibleWhen } : parameter;
}
const integerKeys: Record<string, true> = {
  maxPoints: true, petals: true, resolution: true, hillCount: true, levels: true,
  beadPetals: true, grid: true, attempts: true, markPetals: true, columns: true, rows: true, depth: true, iterations: true,
};
const n = (key: string, label: string, description: string, min: number, max: number, step: number,
  hardMin: number, hardMax: number, visibleWhen?: Condition): Parameter =>
  control(numeric(key, label, description, min, max, step,
    { hardMin, hardMax, integer: integerKeys[key] === true }), visibleWhen);
const select = (key: string, label: string, description: string, options: string[],
  visibleWhen?: Condition): Parameter => control(choice(key, label, description, options), visibleWhen);

